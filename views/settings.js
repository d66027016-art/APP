import { h } from '../lib/preact.module.js';
import { useState, useRef } from '../lib/hooks.module.js';
import htm from '../lib/htm.module.js';
import { Card, Button, Input, Select, Icon } from '../components.js';

const html = htm.bind(h);

export default function Settings({ 
  currencySymbol, 
  setCurrencySymbol, 
  setView, 
  onBackupExport, 
  onBackupImport,
  onTriggerTestNotification 
}) {
  const fileInputRef = useRef(null);
  const [importStatus, setImportStatus] = useState('');
  const [isDarkMode, setIsDarkMode] = useState(document.documentElement.classList.contains('dark'));

  const handleThemeToggle = () => {
    const isDark = document.documentElement.classList.toggle('dark');
    setIsDarkMode(isDark);
    localStorage.setItem('theme', isDark ? 'dark' : 'light');
  };

  const handleExportClick = async () => {
    try {
      const backupString = await onBackupExport();
      
      // Copy to clipboard
      await navigator.clipboard.writeText(backupString);
      
      // Trigger File Download
      const dataUri = 'data:application/json;charset=utf-8,'+ encodeURIComponent(backupString);
      const exportFileDefaultName = `finance_by_pooja_backup_${new Date().toISOString().split('T')[0]}.json`;
      
      const linkElement = document.createElement('a');
      linkElement.setAttribute('href', dataUri);
      linkElement.setAttribute('download', exportFileDefaultName);
      linkElement.click();
      
      alert("Backup successfully exported! The JSON backup has been copied to your clipboard and downloaded as a file.");
    } catch (err) {
      console.error(err);
      alert("Failed to export backup: " + err.message);
    }
  };

  const handleImportFileChange = async (e) => {
    const file = e.target.files[0];
    if (!file) return;

    if (!confirm("WARNING: Importing this backup will OVERWRITE all current borrower, loan, and payment records in IndexedDB. This action cannot be undone. Do you wish to proceed?")) {
      e.target.value = '';
      return;
    }

    setImportStatus('reading');
    const reader = new FileReader();
    reader.onload = async (evt) => {
      try {
        const jsonContent = evt.target.result;
        await onBackupImport(jsonContent);
        setImportStatus('success');
        alert("Ledger successfully restored from backup!");
        setView({ name: 'dashboard' });
      } catch (err) {
        console.error(err);
        setImportStatus('error');
        alert("Failed to restore backup: Please ensure it is a valid backup file generated by this application.");
      }
    };
    reader.readAsText(file);
    e.target.value = ''; // Reset file input
  };

import { requestNotificationPermission, triggerNotificationSignal } from '../notification-service.js';

  const handleRequestPermission = async () => {
    const res = await requestNotificationPermission();
    alert(res.message);
    if (res.success) {
      await triggerNotificationSignal("Finance by Pooja", "Notifications enabled for payment reminders!");
    }
  };

  const handleTestAlert = async () => {
    const sent = await triggerNotificationSignal("Finance by Pooja", "Test Alert: Payment reminder notification active!");
    if (sent) {
      alert("Test notification sent!");
    } else {
      alert("Permission granted. Sample notification triggered.");
    }
  };

  return html`
    <div class="page-transition max-w-2xl mx-auto flex flex-col gap-6">
      
      <!-- Header -->
      <div class="flex items-center gap-4">
        <${Button} variant="ghost" onClick=${() => setView({ name: 'dashboard' })} className="p-2 rounded-lg">
          <${Icon} name="arrowLeft" className="w-5 h-5 text-slate-600 dark:text-slate-300" />
        <//>
        <div>
          <h2 class="text-xl font-bold text-slate-800 dark:text-slate-100">Application Settings</h2>
          <p class="text-xs text-slate-550 dark:text-slate-400">Configure visual themes, defaults, backups, and notification preferences</p>
        </div>
      </div>

      <!-- Settings Layout -->
      <div class="flex flex-col gap-5">
        
        <!-- Theme & Localization -->
        <${Card} className="flex flex-col gap-4">
          <h3 class="text-sm font-bold text-slate-800 dark:text-slate-200 uppercase tracking-wider border-b border-slate-100 dark:border-slate-800 pb-2">
            Preferences & Appearance
          </h3>

          <div class="flex items-center justify-between py-2 border-b border-slate-100 dark:border-slate-850">
            <div>
              <p class="text-sm font-bold text-slate-800 dark:text-slate-200">Dark Mode Interface</p>
              <p class="text-xs text-slate-500 dark:text-slate-400 mt-0.5">Toggle between sophisticated dark mode and light theme layouts</p>
            </div>
            <button 
              onClick=${handleThemeToggle} 
              class="w-11 h-6 rounded-full p-0.5 transition-colors focus:outline-none ${isDarkMode ? 'bg-brand-600' : 'bg-slate-350 dark:bg-slate-700'}"
            >
              <div class="w-5 h-5 rounded-full bg-white transition-transform ${isDarkMode ? 'translate-x-5' : 'translate-x-0'} flex items-center justify-center shadow-sm">
                <${Icon} name=${isDarkMode ? 'settings' : 'user'} className="w-3 h-3 text-slate-400" />
              </div>
            </button>
          </div>

          <div class="flex flex-col sm:flex-row justify-between sm:items-center gap-3 pt-1">
            <div>
              <p class="text-sm font-bold text-slate-800 dark:text-slate-200">Currency Symbol</p>
              <p class="text-xs text-slate-500 dark:text-slate-400 mt-0.5">Specify the default currency character displayed in the app</p>
            </div>
            <div class="w-32">
              <${Input} 
                value=${currencySymbol} 
                onChange=${e => setCurrencySymbol(e.target.value)} 
                placeholder="e.g. ₹" 
                className="w-full text-right"
              />
            </div>
          </div>
        <//>

        <!-- Web Notifications Preferences -->
        <${Card} className="flex flex-col gap-4">
          <h3 class="text-sm font-bold text-slate-800 dark:text-slate-200 uppercase tracking-wider border-b border-slate-100 dark:border-slate-800 pb-2">
            Reminder Notifications
          </h3>
          <p class="text-xs text-slate-500 dark:text-slate-400">Trigger standard Web Alerts for payments that are due today, upcoming, or past due.</p>
          
          <div class="flex flex-wrap gap-3 mt-1">
            <${Button} variant="secondary" className="text-xs" onClick=${handleRequestPermission}>
              <${Icon} name="bell" className="w-4 h-4 text-brand-600 dark:text-brand-450" /> Enable Notifications
            <//>
            <${Button} variant="ghost" className="text-xs text-slate-500 hover:bg-slate-50 dark:hover:bg-slate-800" onClick=${handleTestAlert}>
              Test Alert Signal
            <//>
          </div>
        <//>

        <!-- Data Backup & Recovery Operations -->
        <${Card} className="flex flex-col gap-4 border border-slate-150 dark:border-slate-850">
          <h3 class="text-sm font-bold text-slate-800 dark:text-slate-200 uppercase tracking-wider border-b border-slate-100 dark:border-slate-800 pb-2">
            Database Backup & Restore
          </h3>
          <p class="text-xs text-slate-500 dark:text-slate-400">
            Export all records (loans, payments, borrower details) to a local backup file, or restore from a previous session. 
            All processing is client-side; no data is ever uploaded.
          </p>

          <div class="flex flex-wrap gap-3 mt-2 border-t border-slate-100 dark:border-slate-850 pt-4">
            <${Button} variant="primary" className="text-xs" onClick=${handleExportClick}>
              <${Icon} name="download" className="w-4 h-4" /> Create & Download Backup
            <//>
            
            <input 
              type="file" 
              ref=${fileInputRef} 
              onChange=${handleImportFileChange} 
              accept=".json" 
              class="hidden" 
            />
            <${Button} variant="secondary" className="text-xs border-slate-205 dark:border-slate-700" onClick=${() => fileInputRef.current.click()}>
              <${Icon} name="upload" className="w-4 h-4 text-slate-450 dark:text-slate-400" /> Restore From Backup
            <//>
          </div>

          ${importStatus === 'reading' && html`<p class="text-xs text-brand-600 dark:text-brand-400 mt-2 font-medium">Restoring records from backup file...</p>`}
        <//>

      </div>
    </div>
  `;
}


